import {loadVocabulary} from '../src/vocabulary/node.ts';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync,mkdtempSync,copyFileSync} from 'node:fs';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
const root=fileURLToPath(new URL('../',import.meta.url));const dir=join(root,'work/standalone-generated');
const compiler=process.env.OSF_BUN??'bun';
const canonical=await loadVocabulary(join(root,'knowledge'));
const snapshot=JSON.parse(readFileSync(join(dir,'knowledge.json'),'utf8'));
assert.deepEqual(snapshot.entries,JSON.parse(JSON.stringify(canonical.entries)));
assert.deepEqual(snapshot.resources,JSON.parse(JSON.stringify(canonical.resources)));
assert.deepEqual(snapshot.enrichments,JSON.parse(JSON.stringify(canonical.enrichments)));
const program=`import assert from 'node:assert/strict';
import {Vocabulary,readerQuantity,scaleReaderQuantity,convertReaderUnit,convertReaderDensity,createReferencePage,renderReferenceHtml,parseRecipe,renderCompact} from '../../src/index.ts';
import snapshot from './knowledge.json' with {type:'json'};
const v=new Vocabulary(snapshot.entries,snapshot);
const cups=readerQuantity('2 cups');const scaled=scaleReaderQuantity(cups,2);assert.equal(scaled.amount,4);assert.equal(scaled.unit,'cups');
assert.equal(scaleReaderQuantity(cups,1.5).amount,3);
assert.equal(convertReaderUnit(cups,'ml'),undefined);
assert.deepEqual(convertReaderDensity([],readerQuantity('1 US cup'),{to:'g',target:{kind:'ingredient',id:'flour'}}),{ok:false,reason:'no-applicable-record'});
const grams=convertReaderUnit(readerQuantity('1kg'),'g');assert.equal(grams.amount,1000);
const fahrenheit=convertReaderUnit(readerQuantity('100c'),'°F');assert.equal(fahrenheit.amount,212);
const html=renderReferenceHtml(createReferencePage(v,'ingredient','carrot'));
assert.ok(html.includes('carrot'));
console.log(JSON.stringify({entries:v.entries,resources:v.resources,enrichments:v.enrichments,scaled,grams,fahrenheit,custom:scaleReaderQuantity(readerQuantity('2 scoops'),1.5),html,render:renderCompact(parseRecipe('::recipe\\nname: Crème 日本語\\n::ingredients\\n(flour) 250g\\n',{vocabulary:v}),{vocabulary:v})}));
`;
writeFileSync(join(dir,'library-probe.js'),program);
const exe=join(dir,process.platform==='win32'?'library-probe.exe':'library-probe');
const compiled=spawnSync(compiler,['--no-env-file','build','--compile',join(dir,'library-probe.js'),'--outfile',exe],{cwd:root,encoding:'utf8'});assert.equal(compiled.status,0,compiled.stderr);
const outside=mkdtempSync(join(tmpdir(),'opensauce portable library '));const copied=join(outside,process.platform==='win32'?'probe.exe':'probe');copyFileSync(exe,copied);mkdirSync(join(outside,'empty'));
const env:NodeJS.ProcessEnv={PATH:join(outside,'empty'),HOME:outside,USERPROFILE:outside,TEMP:outside,TMP:outside};for(const key of ['SystemRoot','WINDIR'])if(process.env[key])env[key]=process.env[key];
const options={cwd:outside,env,maxBuffer:32*1024*1024};
const node=spawnSync(process.execPath,[join(dir,'library-probe.js')],options),bun=spawnSync(copied,[],options);
assert.equal(node.status,0,node.stderr.toString());assert.equal(bun.status,0,bun.stderr.toString());assert.deepEqual(bun.stdout,node.stdout);assert.deepEqual(bun.stderr,node.stderr);
console.log(JSON.stringify({portableLibrary:'passed',knowledge:'all entries/resources/enrichments byte-equivalent',operations:'same-unit scaling, ambiguous units, density refusal, mass/temperature conversion, reference rendering, Unicode rendering',outside}));
